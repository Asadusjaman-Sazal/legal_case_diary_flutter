/// Emits the Supabase reference-data seed migration from the app's own seed
/// constants, so Drift, Supabase and backups can never disagree about the
/// stable deterministic IDs of built-in rows (implementation_plan.md Rev 2.4
/// §1; Task 04 holds the client copy).
///
///   dart run tool/generate_supabase_seed.dart          # writes the migration
///   dart run tool/generate_supabase_seed.dart --check  # fails if it is stale
///
/// The output is byte-stable on purpose: [seedUpdatedAtMs] is a fixed constant
/// rather than "now", so re-running the generator without a seed change leaves
/// the file untouched and `--check` is a real guard. Line endings are always
/// LF; the parity test normalizes CRLF checkouts before comparing.
library;

import 'dart:io';

import 'package:legal_case_diary/core/constants/pre_seeded_data.dart';

/// Client `updated_at` stamped on every seeded row, in epoch milliseconds.
///
/// A fixed instant (2026-01-01T00:00:00Z) keeps the generated file
/// deterministic; it is display metadata only and never decides write
/// acceptance. `server_updated_at` is set by the trigger at apply time.
const int seedUpdatedAtMs = 1767225600000;

/// Generated migration, relative to the project root. The timestamp prefix is
/// fixed so the committed file name never moves.
const String seedMigrationPath =
    'supabase/migrations/20260929100200_phase1_seed_reference_data.sql';

const String _header = '''-- Phase 1 — Built-in reference data, generated by tool/generate_supabase_seed.dart.
-- Do not edit by hand: change lib/core/constants/pre_seeded_data.dart and re-run
--   dart run tool/generate_supabase_seed.dart
--
-- Every ID here is the stable deterministic tag the Drift seed migrations
-- (Task 04) already use, so a device, the server and a backup all name the same
-- row. Rows are upserted with `on conflict (id) do update ... where
-- is_user_modified = false`, mirroring the client's seed runner: a row the user
-- or firm has customized is never overwritten by a later seed. `version` starts
-- at 1 (the server's insert revision) and re-seeding never bumps it; the
-- `server_updated_at` trigger stamps the pull cursor.
--
-- Table class: all six tables are push/pull domain (editable, firm-shared
-- reference data with user-scoped customizations in individual mode).
''';

/// SQL literal for an optional text value.
String _text(String? value) =>
    value == null ? 'null' : "'${value.replaceAll("'", "''")}'";

/// One upsert statement: target table, column list, value rows and the subset
/// of columns a re-seed refreshes (the data columns, exactly as the Drift seed
/// runner refreshes them).
class _Upsert {
  const _Upsert({
    required this.table,
    required this.columns,
    required this.rows,
    required this.refreshed,
  });

  final String table;
  final List<String> columns;
  final List<List<String>> rows;
  final List<String> refreshed;

  String emit() {
    if (rows.isEmpty) return '';
    final buffer = StringBuffer()
      ..writeln('insert into public.$table (${columns.join(', ')})')
      ..writeln('values');
    for (var i = 0; i < rows.length; i++) {
      buffer.write('  (${rows[i].join(', ')})');
      buffer.writeln(i == rows.length - 1 ? '' : ',');
    }
    // The conflict target is `id` on every reference table; a re-seed refreshes
    // only the data columns, and only while the row is not user-modified.
    buffer.writeln('on conflict (id) do update set');
    buffer.writeln(refreshed
        .map((column) => '  $column = excluded.$column')
        .join(',\n'));
    buffer.writeln('where $table.is_user_modified = false;');
    return buffer.toString();
  }
}

/// Shared sync-column literal tails: built-in rows are never custom, never
/// user-modified, unsynced and not deleted.
const String _syncTail =
    'false, false, null, null, $seedUpdatedAtMs, 1, null, false, null';

/// Builds the complete seed migration text.
String buildReferenceSeedSql() {
  final statements = <String>[];

  statements.add(_Upsert(
    table: 'court_categories',
    columns: const [
      'id', 'name_key', 'court_level', 'order_index', 'division', 'district',
      'is_custom', 'is_user_modified', 'user_id', 'firm_id', 'updated_at',
      'version', 'synced_at', 'is_deleted', 'last_modified_by',
    ],
    rows: [
      for (final category in seedCategories)
        [
          _text(category.id),
          _text(category.nameKey),
          _text(category.courtLevel),
          '${category.orderIndex}',
          'null',
          'null',
          _syncTail,
        ],
    ],
    refreshed: const ['name_key', 'court_level', 'order_index', 'updated_at'],
  ).emit());

  statements.add(_Upsert(
    table: 'case_categories',
    columns: const [
      'id', 'court_category_id', 'name', 'order_index', 'is_custom',
      'is_user_modified', 'user_id', 'firm_id', 'updated_at', 'version',
      'synced_at', 'is_deleted', 'last_modified_by',
    ],
    rows: [
      for (final category in seedCategories)
        for (final caseCategory in category.caseCategories)
          [
            _text(caseCategory.id),
            _text(category.id),
            _text(caseCategory.labelEn),
            '${caseCategory.orderIndex}',
            _syncTail,
          ],
    ],
    refreshed: const [
      'court_category_id', 'name', 'order_index', 'updated_at',
    ],
  ).emit());

  statements.add(_Upsert(
    table: 'steps',
    columns: const [
      'id', 'court_category_id', 'step_name', 'order_index', 'is_custom',
      'is_user_modified', 'user_id', 'firm_id', 'updated_at', 'version',
      'synced_at', 'is_deleted', 'last_modified_by',
    ],
    rows: [
      for (final category in seedCategories)
        for (final step in category.steps)
          [
            _text(step.id),
            _text(category.id),
            _text(step.labelEn),
            '${step.orderIndex}',
            _syncTail,
          ],
    ],
    refreshed: const [
      'court_category_id', 'step_name', 'order_index', 'updated_at',
    ],
  ).emit());

  statements.add(_Upsert(
    table: 'case_types',
    columns: const [
      'id', 'court_category_id', 'case_category_id', 'name', 'order_index',
      'is_custom', 'is_user_modified', 'user_id', 'firm_id', 'updated_at',
      'version', 'synced_at', 'is_deleted', 'last_modified_by',
    ],
    rows: [
      for (final category in seedCategories)
        for (final caseType in category.allCaseTypes)
          [
            _text(caseType.id),
            _text(category.id),
            _text(caseType.caseCategoryId),
            _text(caseType.labelEn),
            '${caseType.orderIndex}',
            _syncTail,
          ],
    ],
    refreshed: const [
      'court_category_id', 'case_category_id', 'name', 'order_index',
      'updated_at',
    ],
  ).emit());

  statements.add(_Upsert(
    table: 'on_behalfs',
    columns: const [
      'id', 'court_category_id', 'name', 'order_index', 'is_custom',
      'is_user_modified', 'user_id', 'firm_id', 'updated_at', 'version',
      'synced_at', 'is_deleted', 'last_modified_by',
    ],
    rows: [
      for (final category in seedCategories)
        for (final onBehalf in category.onBehalfs)
          [
            _text(onBehalf.id),
            _text(category.id),
            _text(onBehalf.labelEn),
            '${onBehalf.orderIndex}',
            _syncTail,
          ],
    ],
    refreshed: const [
      'court_category_id', 'name', 'order_index', 'updated_at',
    ],
  ).emit());

  statements.add(_Upsert(
    table: 'courts',
    columns: const [
      'id', 'court_name', 'higher_lower_courts', 'division', 'district',
      'court_category_id', 'order_index', 'is_custom', 'is_user_modified',
      'user_id', 'firm_id', 'updated_at', 'version', 'synced_at', 'is_deleted',
      'last_modified_by',
    ],
    rows: [
      for (final court in allSeedCourts)
        [
          _text(court.id),
          _text(court.courtNameEn),
          _text(court.higherLowerCourts),
          _text(court.division),
          _text(court.district),
          _text(court.courtCategoryId),
          '${court.orderIndex}',
          _syncTail,
        ],
    ],
    refreshed: const [
      'court_name', 'higher_lower_courts', 'division', 'district',
      'court_category_id', 'order_index', 'updated_at',
    ],
  ).emit());

  final body = statements.where((statement) => statement.isNotEmpty).join('\n');
  return '$_header\n$body\n';
}

/// Normalizes line endings so a CRLF checkout and the generator's LF output
/// compare equal.
String normalizeSql(String sql) => sql.replaceAll('\r\n', '\n');

void main(List<String> args) {
  final check = args.contains('--check');
  final generated = normalizeSql(buildReferenceSeedSql());
  final file = File(seedMigrationPath);

  if (check) {
    if (!file.existsSync()) {
      stderr.writeln('MISSING: $seedMigrationPath has not been generated.');
      exit(1);
    }
    if (normalizeSql(file.readAsStringSync()) != generated) {
      stderr.writeln(
        'STALE: $seedMigrationPath does not match the current seed data. '
        'Run: dart run tool/generate_supabase_seed.dart',
      );
      exit(1);
    }
    stdout.writeln('OK: $seedMigrationPath is up to date.');
    return;
  }

  file.writeAsStringSync(generated);
  final steps = seedCategories.fold<int>(
    0,
    (total, category) => total + category.steps.length,
  );
  final caseTypes = seedCategories.fold<int>(
    0,
    (total, category) => total + category.allCaseTypes.length,
  );
  final onBehalfs = seedCategories.fold<int>(
    0,
    (total, category) => total + category.onBehalfs.length,
  );
  final caseCategories = seedCategories.fold<int>(
    0,
    (total, category) => total + category.caseCategories.length,
  );
  stdout.writeln(
    'Wrote $seedMigrationPath — ${seedCategories.length} court categories, '
    '$caseCategories case categories, $steps steps, $caseTypes case types, '
    '$onBehalfs on-behalf roles, ${allSeedCourts.length} courts.',
  );
}
